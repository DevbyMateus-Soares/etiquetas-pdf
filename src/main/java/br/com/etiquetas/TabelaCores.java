    private static final Map<String, String> CORES = carregar();

    private TabelaCores(){
        // Classe ultilitaria não precisa ser instânciada
    }

    /** devolve o nome da cor, ou vazio caso a combinação padrão PRODUTO + CÓDIGO não existir na tabela.**/
     public static Optional<String> buscar (String produto, String codigoCor){
         return Optional.ofNullable(CORES.get(chave(produto,codigoCor)));
     }

     private static Map<String, String> carregar(){
         Map<String, String> mapa = new HashMap<>();
         for (String linha : DADOS.split("\n")) {
             if (linha.isBlank()) {
                 continue;
             }

             String[] partes = linha.split(";",3);
             mapa.put(chave(partes[0], partes[1]), partes[2].trim());
         }
         return Map.copyOf(mapa);
     }

    private static String chave(String produto, String codigoCor){
         return produto.trim().toUpperCase() + "|" + codigoCor.trim();
    }
